namespace rajadordev\autoupdater\api\logger;

use rajadordev\autoupdater\Loader;
use SmartCommand\utils\SingletonTrait;

class AutoPluginUpdaterLogger extends Logger
{

    use SingletonTrait;

    public static function init(Loader $plugin) : self
    {
        $instance = new self($plugin->getDataFolder() . 'auto_updater.log', $plugin->getLogger());
        self::setInstance($instance);
        return $instance;
    }

    
}